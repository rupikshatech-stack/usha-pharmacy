import { z } from 'zod';
import { BUSINESS_CATEGORIES, ORGANIZATION_STATUSES } from '../models/Organization.js';

/**
 * What may be sent when onboarding a pharmacy.
 *
 * The owner's name and email are required, because they become a real account that somebody has to sign in to.
 * Everything else about the pharmacy can be filled in later by the pharmacy itself on the Settings screens, so
 * demanding it here would only slow down the person on the phone.
 */
const trimmed = (max) => z.string().trim().max(max);

export const createOrganizationSchema = z.object({
  name: z.string().trim().min(2, 'Give the pharmacy a name of at least 2 characters').max(150),
  businessCategory: z.enum(BUSINESS_CATEGORIES).optional(),
  email: trimmed(150).email('Enter a valid email address').optional().or(z.literal('')),
  phone: trimmed(20).optional(),
  address: z
    .object({
      line1: trimmed(200).optional(),
      line2: trimmed(200).optional(),
      landmark: trimmed(120).optional(),
      city: trimmed(80).optional(),
      state: trimmed(80).optional(),
      pincode: trimmed(10).optional(),
      country: trimmed(60).optional(),
    })
    .optional(),
  owner: z.object({
    firstName: z.string().trim().min(1, "The owner's first name is required").max(60),
    lastName: trimmed(60).optional(),
    email: z.string().trim().toLowerCase().email('Enter a valid email address for the owner'),
    phone: trimmed(20).optional(),
  }),
  // The temporary password is generated by the server. Accepting one would let an operator set a password a
  // pharmacy never chose, and put it in a request body and a log.
  temporaryPassword: z.undefined({ error: 'The temporary password is generated by the server; do not send one.' }).optional(),
  password: z.undefined({ error: 'The temporary password is generated by the server; do not send one.' }).optional(),
});

export const organizationListQuery = z.object({
  search: z.string().trim().max(100).optional(),
  // Narrowing the list is a reading convenience, so an unknown status is a mistake worth reporting rather than
  // quietly ignoring: a filter that silently does nothing looks exactly like data that is not there.
  status: z.enum(ORGANIZATION_STATUSES).optional(),
  page: z.coerce.number().int().min(1).default(1),
  limit: z.coerce.number().int().min(1).max(100).default(20),
});
