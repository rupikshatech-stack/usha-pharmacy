import { useState } from 'react';
import { Building2, Check, Copy, Plus, TriangleAlert } from 'lucide-react';
import { Button, Card, Input, Select, cx } from '../../components/common/ui';
import { platformService } from '../../services/platformService';
import { useFetch } from '../../hooks/useFetch';

const BLANK = {
  name: '',
  businessCategory: 'retail',
  phone: '',
  address: { line1: '', city: '', state: '', pincode: '' },
  owner: { firstName: '', lastName: '', email: '', phone: '' },
};

const CATEGORIES = [
  ['retail', 'Retail pharmacy'],
  ['wholesale', 'Wholesale'],
  ['both', 'Retail and wholesale'],
  ['hospital', 'Hospital pharmacy'],
];

/**
 * Onboarding a pharmacy, and the one screen that ever shows its first credentials.
 *
 * The credentials panel is the reason this page exists rather than a curl command: the temporary password is
 * generated by the server, returned once, and stored nowhere. If it is lost before it reaches the client, the only
 * remedy is for someone to reset it — so the panel says so plainly and does not pretend it can be fetched again.
 */
export default function NewOrganization() {
  const [form, setForm] = useState(BLANK);
  const [created, setCreated] = useState(null);
  const [error, setError] = useState(null);
  const [busy, setBusy] = useState(false);
  const [copied, setCopied] = useState(false);
  const existing = useFetch('/platform/organizations', { limit: 100 });

  const set = (path) => (e) => {
    const value = e.target.value;
    setForm((f) => {
      const [head, leaf] = path.split('.');
      return leaf ? { ...f, [head]: { ...f[head], [leaf]: value } } : { ...f, [head]: value };
    });
  };

  const submit = async (e) => {
    e.preventDefault();
    setBusy(true);
    setError(null);
    try {
      const data = await platformService.createOrganization(form);
      setCreated(data);
      setForm(BLANK);
      existing.reload();
    } catch (err) {
      setError(err.message);
    } finally {
      setBusy(false);
    }
  };

  const copy = async () => {
    const text = `Pharmacy: ${created.organization.name}\nSign in at: ${window.location.origin}/login\nEmail: ${created.administrator.email}\nTemporary password: ${created.temporaryPassword}\n\nYou will be asked to choose your own password the first time you sign in.`;
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      /* clipboard refused (insecure context or denied) — the values are on screen to copy by hand */
    }
  };

  if (created) {
    return (
      <Card className="p-6">
        <div className="flex items-start gap-3">
          <div className="grid h-10 w-10 shrink-0 place-items-center rounded-xl bg-success-soft text-success">
            <Check className="h-5 w-5" aria-hidden="true" />
          </div>
          <div className="min-w-0">
            <h2 className="text-lg font-bold">{created.organization.name} is set up</h2>
            <p className="mt-0.5 text-sm text-muted">Five built-in roles were created, and the owner is its first administrator.</p>
          </div>
        </div>

        {/* The one and only sight of these. */}
        <div className="mt-5 rounded-2xl border border-warning/40 bg-warning/10 p-4">
          <p className="flex items-start gap-2 text-sm font-semibold">
            <TriangleAlert className="mt-0.5 h-4 w-4 shrink-0 text-warning" aria-hidden="true" />
            Shown once. Copy these now — the password is stored nowhere and cannot be shown again.
          </p>
          <dl className="mt-3 grid gap-2 text-sm sm:grid-cols-[10rem_1fr]">
            <dt className="text-muted">Sign in at</dt>
            <dd className="font-mono">{window.location.origin}/login</dd>
            <dt className="text-muted">Email</dt>
            <dd className="font-mono font-semibold" data-testid="new-org-email">{created.administrator.email}</dd>
            <dt className="text-muted">Temporary password</dt>
            <dd className="select-all font-mono text-base font-bold tracking-wide" data-testid="new-org-password">{created.temporaryPassword}</dd>
          </dl>
          <div className="mt-3 flex flex-wrap gap-2">
            <Button variant="secondary" onClick={copy}>
              <Copy className="h-4 w-4" aria-hidden="true" /> {copied ? 'Copied' : 'Copy for the client'}
            </Button>
            <Button onClick={() => setCreated(null)}>
              <Plus className="h-4 w-4" aria-hidden="true" /> Onboard another
            </Button>
          </div>
          <p className="mt-3 text-xs text-muted">{created.note}</p>
        </div>
      </Card>
    );
  }

  return (
    <div className="space-y-4">
      <Card className="p-6">
        <h2 className="flex items-center gap-2 text-lg font-bold">
          <Building2 className="h-5 w-5 text-muted" aria-hidden="true" /> Onboard a pharmacy
        </h2>
        <p className="mt-0.5 text-sm text-muted">Creates the pharmacy, its five built-in roles, and its first administrator in one step.</p>

        <form onSubmit={submit} className="mt-5 space-y-5">
          <fieldset className="space-y-3">
            <legend className="text-[11px] font-bold uppercase tracking-wide text-muted">The pharmacy</legend>
            <div className="grid gap-3 sm:grid-cols-2">
              <Input label="Pharmacy name" required value={form.name} onChange={set('name')} placeholder="e.g. Shree Medical Stores" autoComplete="off" />
              <Select label="Business category" value={form.businessCategory} onChange={set('businessCategory')}>
                {CATEGORIES.map(([v, l]) => <option key={v} value={v}>{l}</option>)}
              </Select>
            </div>
            <div className="grid gap-3 sm:grid-cols-2">
              <Input label="Address" value={form.address.line1} onChange={set('address.line1')} placeholder="Street address" autoComplete="off" />
              <Input label="Phone" value={form.phone} onChange={set('phone')} inputMode="numeric" autoComplete="off" />
            </div>
            <div className="grid gap-3 sm:grid-cols-3">
              <Input label="City" value={form.address.city} onChange={set('address.city')} autoComplete="off" />
              <Input label="State" value={form.address.state} onChange={set('address.state')} autoComplete="off" />
              <Input label="PIN code" value={form.address.pincode} onChange={set('address.pincode')} inputMode="numeric" autoComplete="off" />
            </div>
          </fieldset>

          <fieldset className="space-y-3">
            <legend className="text-[11px] font-bold uppercase tracking-wide text-muted">The owner — becomes the first administrator</legend>
            <div className="grid gap-3 sm:grid-cols-2">
              <Input label="First name" required value={form.owner.firstName} onChange={set('owner.firstName')} autoComplete="off" />
              <Input label="Last name" value={form.owner.lastName} onChange={set('owner.lastName')} autoComplete="off" />
            </div>
            <div className="grid gap-3 sm:grid-cols-2">
              <Input label="Email" required type="email" value={form.owner.email} onChange={set('owner.email')} hint="They sign in with this. It must not already have an account." autoComplete="off" />
              <Input label="Phone" value={form.owner.phone} onChange={set('owner.phone')} inputMode="numeric" autoComplete="off" />
            </div>
          </fieldset>

          {error && <p role="alert" className="rounded-xl border border-danger/40 bg-danger-soft px-3 py-2 text-sm text-danger">{error}</p>}

          <Button type="submit" loading={busy}>
            <Plus className="h-4 w-4" aria-hidden="true" /> Create pharmacy
          </Button>
        </form>
      </Card>

      <Card className="overflow-hidden">
        <div className="border-b border-line bg-subtle/40 px-4 py-2.5 text-[11px] font-bold uppercase tracking-wide text-muted">
          Already on this installation {existing.data ? `(${existing.data.total})` : ''}
        </div>
        {existing.loading && !existing.data ? (
          <p className="p-4 text-sm text-muted">Loading…</p>
        ) : (existing.data?.items || []).length === 0 ? (
          <p className="p-4 text-sm text-muted">No pharmacies yet.</p>
        ) : (
          <ul className="divide-y divide-line">
            {existing.data.items.map((o) => (
              <li key={o.id} className="flex flex-wrap items-center justify-between gap-2 px-4 py-2.5 text-sm">
                <div className="min-w-0">
                  <span className="font-medium">{o.name}</span>
                  <span className="ml-2 text-xs text-muted">{[o.city, o.state].filter(Boolean).join(', ')}</span>
                </div>
                <span className={cx('text-xs', o.status === 'active' ? 'text-muted' : 'text-danger')}>
                  {o.ownerEmail || '—'}{o.status !== 'active' ? ` · ${o.status}` : ''}
                </span>
              </li>
            ))}
          </ul>
        )}
      </Card>
    </div>
  );
}
